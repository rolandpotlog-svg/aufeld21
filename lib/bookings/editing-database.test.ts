import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { PGlite } from '@electric-sql/pglite';
import { btree_gist } from '@electric-sql/pglite/contrib/btree_gist';

const owner = '00000000-0000-4000-8000-000000000001';
const staff = '00000000-0000-4000-8000-000000000002';
const other = '00000000-0000-4000-8000-000000000003';
const load = (name: string) => readFile(new URL(`../../supabase/migrations/${name}`, import.meta.url), 'utf8');

test('real PostgreSQL update policy/trigger: ownership, overlap, quota, months, billing locks and unlimited access', async () => {
  const db = new PGlite({ extensions: { btree_gist } });
  try {
    await db.exec(`create extension btree_gist;
      create role anon; create role authenticated; create role service_role bypassrls;
      create schema auth; grant usage on schema auth to authenticated;
      create table auth.users(id uuid primary key);
      create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;
      create function auth.jwt() returns jsonb language sql as $$select '{"role":"service_role"}'::jsonb$$;
      create function public.is_admin() returns boolean language sql as $$select true$$;
      create function public.is_member() returns boolean language sql as $$select true$$;`);
    const initial = await load('001_initial_schema.sql');
    await db.exec(initial.slice(initial.indexOf('create table if not exists public.members'), initial.indexOf('create index if not exists bookings_start_at_idx')));
    await db.exec('create sequence public.invoice_number_seq');
    for (const filename of ['011_atomic_invoice_numbers.sql', '20260906183145_invoice_reliability_and_portal_safety.sql', '20260907201350_meeting_package_terms.sql', '20260924085420_unlimited_meeting_access.sql']) await db.exec(await load(filename));
    await db.exec(`create or replace function public.is_member() returns boolean language sql stable security definer set search_path='' as $$select exists(select 1 from public.members where id=auth.uid() and active)$$;
      alter table public.bookings enable row level security;
      create policy "Read bookings" on public.bookings for select to authenticated using(public.is_member());
      grant select on public.bookings to authenticated;
      insert into auth.users values('${owner}'),('${staff}'),('${other}');
      insert into members(id,email,name,role) values('${owner}','owner@test.example','Owner','admin'),('${staff}','staff@test.example','Staff','employee'),('${other}','other@test.example','Other','member');`);
    await db.exec(await load('20261119102628_editable_meeting_bookings.sql'));
    const m = (await db.query<{ m: string }>("select (date_trunc('month',now() at time zone 'Europe/Vienna')+interval '1 month')::date::text m")).rows[0].m;
    const n = (await db.query<{ m: string }>("select ($1::date+interval '1 month')::date::text m", [m])).rows[0].m;
    await db.query("insert into meeting_terms(member_id,effective_month,account_id,package,included_hours) values($1,$3,$1,'custom',2),($2,$3,$1,'shared',0),($1,$4,$1,'custom',1)", [owner, staff, m, n]);
    const book = async (id: string, day: number, hours: number) => (await db.query<{ id: string }>("insert into bookings(member_id,start_at,end_at,note) values($1,($2::date+$3::int+time '08:00') at time zone 'Europe/Vienna',($2::date+$3::int+time '08:00'+make_interval(hours=>$4::int)) at time zone 'Europe/Vienna','original') returning id", [id, m, day, hours])).rows[0].id;
    const ownId = await book(staff, 1, 2);
    const otherId = await book(other, 2, 2);
    const before = JSON.stringify((await db.query('select * from invoices')).rows);
    const login = async (id: string) => { await db.exec('reset role'); await db.query("select set_config('request.jwt.claim.sub',$1,false)", [id]); await db.exec('set role authenticated'); };
    const move = (id: string, date: string, time: string, hours: number) => db.query("update bookings set start_at=($2::date+$3::time) at time zone 'Europe/Vienna',end_at=($2::date+$3::time+make_interval(secs=>$4::double precision*3600)) at time zone 'Europe/Vienna' where id=$1 returning id", [id, date, time, hours]);
    await login(staff);
    assert.equal((await move(otherId, m, '11:00', 1)).rows.length, 0);
    assert.equal((await move(ownId, m, '11:00', 2)).rows.length, 1, 'full quota can be moved without double counting');
    await assert.rejects(move(ownId, m, '11:00', 2.5), /employee_quota_exceeded/);
    await assert.rejects(move(ownId, n, '11:00', 2), /employee_quota_exceeded/);
    await assert.rejects(move(ownId, m, '19:00', 2), /bookings_opening_hours/);
    await assert.rejects(move(ownId, m, '11:15', 1), /bookings_half_hour_slots/);
    await assert.rejects(db.query('update bookings set member_id=$2 where id=$1', [ownId, other]), /permission denied/);
    await assert.rejects(db.query('update bookings set id=gen_random_uuid() where id=$1', [ownId]), /permission denied/);
    await assert.rejects(db.query('select billing_private.guard_booking_update()'), /permission denied/);
    const clash = (await db.query<{ date: string }>("select (start_at at time zone 'Europe/Vienna')::date::text date from bookings where id=$1", [otherId])).rows[0].date;
    await assert.rejects(move(ownId, clash, '08:30', 1), /bookings_no_overlap/);
    assert.equal((await move(ownId, clash, '10:00', 1)).rows.length, 1, 'adjacent times allowed');
    assert.equal((await move(ownId, n, '10:00', 1)).rows.length, 1);
    await db.exec('reset role');
    const usage = await db.query<{ used_hours: string }>('select used_hours from meeting_usage($1) where member_id=$2', [m, owner]);
    assert.equal(Number(usage.rows[0].used_hours), 0, 'moving months releases old quota');
    await db.query('update members set active=false where id=$1', [staff]);
    await login(staff);
    assert.equal((await move(ownId, n, '12:00', 1)).rows.length, 0);
    await db.exec('reset role');
    await db.query('update members set active=true where id=$1', [staff]);
    await db.query('update members set meeting_unlimited=true where id=$1', [owner]);
    await login(staff);
    assert.equal((await move(ownId, n, '07:00', 13)).rows.length, 1, 'unlimited remains unlimited');
    await db.exec('reset role');
    assert.equal(JSON.stringify((await db.query('select * from invoices')).rows), before, 'edits never create or change invoices');
    const invoice = (await db.query<{ id: string }>("insert into invoices(member_id,billing_month,issue_date,due_date,service_period_start,service_period_end,created_by) values($1,$2,$2,$2,$2,$2::date+27,$1) returning id", [owner, n])).rows[0].id;
    await db.query('insert into invoice_usage_periods(member_id,usage_month,invoice_id) values($1,$2,$3)', [owner, n, invoice]);
    await login(staff);
    await assert.rejects(move(ownId, n, '09:00', 1), /booking_usage_billed/);
    await db.exec('reset role');
    const pastId = (await db.query<{ id: string }>("insert into bookings(member_id,start_at,end_at) values($1,((current_date-2)+time '08:00') at time zone 'Europe/Vienna',((current_date-2)+time '09:00') at time zone 'Europe/Vienna') returning id", [other])).rows[0].id;
    await login(other);
    assert.equal((await move(pastId, m, '16:00', 1)).rows.length, 0);
    await db.exec('reset role; set role anon');
    await assert.rejects(move(ownId, n, '12:00', 1), /permission denied/);
  } finally { await db.close(); }
});
